// Walks the main flows on a phone viewport and saves screenshots. Usage: node scripts/shots.mjs <url>
import puppeteer from 'puppeteer-core';
const URL = process.argv[2], out = '../screenshots/';
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const p = await b.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const wait = ms => new Promise(r => setTimeout(r, ms));
const click = async (text) => { const ok = await p.evaluate(t => { const el = [...document.querySelectorAll('button')].find(x => x.textContent.trim().includes(t)); if (el) { el.click(); return true; } return false; }, text); if (!ok) errs.push('missing button: ' + text); await wait(500); };
const shot = async (n) => { await wait(700); await p.screenshot({ path: out + n + '.png' }); };
await p.goto(URL, { waitUntil: 'networkidle0' }); await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: 'networkidle0' });
await wait(600); await shot('00-welcome');
{ const r = await p.evaluate(() => { const t = document.querySelector('.s-thumb').getBoundingClientRect(), k = document.querySelector('.slider').getBoundingClientRect(); return { x: t.x + t.width / 2, y: t.y + t.height / 2, end: k.right - 20 }; });
  await p.mouse.move(r.x, r.y); await p.mouse.down(); await p.mouse.move(r.x + 120, r.y, { steps: 8 }); await p.screenshot({ path: out + '00b-welcome-sliding.png' });
  await p.mouse.move(r.end, r.y, { steps: 10 }); await p.mouse.up(); await wait(1500);
  if (await p.evaluate(() => !!document.querySelector('.welcome'))) errs.push('welcome did not close'); }
await shot('01-scan-idle');
await click('Scan this tray'); await wait(900); await p.screenshot({ path: out + '02-scanning.png' });
await wait(2800); await shot('03-results');
await click('Ask the pupil'); await shot('04-feedback-mood');
await click("Didn't like it"); await shot('05-feedback-reason');
await click('Texture'); await wait(900); await shot('06-thanks');
await click('See what the kitchen sees'); await shot('07-dish-detail');
await click('This week'); await wait(1500); await shot('08-insights');
await click('Fix the'); await wait(300); await p.screenshot({ path: out + '09-ai-thinking.png' }); await wait(1600); await shot('10-recipes');
await click('Approve'); await wait(800); await shot('11-menu-updated');
await p.evaluate(() => document.querySelector('.scroll').scrollTo(0, 99999)); await shot('12-verify');
await click('SC'); await shot('13-about');
await p.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 }); await p.reload({ waitUntil: 'networkidle0' }); await shot('14-desktop');
console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no errors');
await b.close();
